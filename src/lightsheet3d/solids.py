"""Nominal profiles of the calibration solids, taken from the course's technical drawings.

The vertices are in `profiles.json`, generated by `scripts/extract_drawing_profiles.py` by reading the vector
front profile of the PDFs (arcs included). Each profile starts at the bottom-left corner
(x = 0, h = 0) and proceeds to the right; x along the solid and h above the resting plane are in mm.
"""
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.signal import find_peaks
from scipy.spatial import cKDTree

PAD = 10.0  # mm of resting plane (h = 0) on each side, so that edge peaks are also recognised


@dataclass(frozen=True)
class Solid:
    name: str
    outline: np.ndarray  # (n, 2) x, h of the vertices, from left to right
    depth: float = 50.0  # mm, extrusion of the solid along x (50 in all drawings)

    @property
    def width(self):
        return float(self.outline[-1, 0] - self.outline[0, 0])

    def peaks(self):
        """(x, height) of each nominal peak; on a flat top it is the centre of the flat stretch."""
        x = np.arange(-PAD, self.width + PAD, 0.01)
        h = np.interp(x, *self.outline.T, left=0.0, right=0.0)
        idx, info = find_peaks(h, prominence=5, plateau_size=1)
        centre = (x[info["left_edges"]] + x[info["right_edges"]]) / 2
        return [(float(c), float(h[i])) for c, i in zip(centre, idx)]


def _load():
    data = json.loads((Path(__file__).parent / "profiles.json").read_text())
    return {key: Solid(v["name"], np.array(v["outline"]), v["depth"]) for key, v in data.items()}


SOLIDS = _load()
CORPO1, CORPO2, CORPO3, CORPO4, CORPO5, CORPO6 = (SOLIDS[f"corpo{n}"] for n in range(1, 7))


def align(solid, y, h, clip=5.0, step=0.1, candidates=4, refine=1.0):
    """(sign, shift) that bring the nominal profile onto the measured profile (y, h).

    The scan's Y reference is arbitrary and may point the opposite way: both are tried.
    The residual is limited to `clip` mm, so unmeasurable stretches (flanks that are too steep) do not
    shift the result. Two steps, no optimiser: the vertical residual on a grid of `step` mm
    chooses the best `candidates` per direction; among these the distance in the (y, h) plane decides, which with
    high noise tells the right direction from the mirrored one when the vertical residual is almost equal.
    """
    y, h = np.asarray(y), np.asarray(h)
    shifts = np.arange(y.min() - solid.width, y.max() + solid.width, step)
    pool = []
    for sign in (1, -1):
        cost = np.empty(len(shifts))
        for i, shift in enumerate(shifts):
            yn, hn = nominal_curve(solid, sign, shift)
            cost[i] = np.minimum(np.abs(h - np.interp(y, yn, hn, left=0.0, right=0.0)), clip).mean()
        chosen = []
        for i in np.argsort(cost):
            if all(abs(shifts[i] - shifts[j]) >= 5 for j in chosen):
                chosen.append(i)
            if len(chosen) == candidates:
                break
        pool += [(sign, shifts[i]) for i in chosen]

    far = y.max() - y.min() + 2 * solid.width  # plane extended beyond every point, so the cost does not depend on the number of points
    best = min(((np.minimum(distances(solid, sign, shift + d, y, h, pad=far), clip).mean(), sign, float(shift + d))
                for sign, shift in pool for d in np.arange(-refine, refine + step / 2, step)))
    return best[1], best[2]


def align_oblique(solid, y, h, clip=5.0, max_scale=1.6):
    """(sign, shift, scale): like `align`, plus the stretch along Y of an oblique cut.

    Direction, scale (from 1 to `max_scale`) and shift are searched together, because with a very oblique cut
    the profile of a nearly symmetric solid can look mirrored: first on a coarse grid with the
    vertical residual limited to `clip` mm, then on a fine grid around the minimum, finally with the distance in the
    (y, h) plane. The scale is always >= 1; the angle between the sheet and the normal to the solid's axis is arccos(1 / scale).
    """
    y, h = np.asarray(y), np.asarray(h)

    def vertical_cost(sign, shift, scale):
        yn, hn = nominal_curve(solid, sign, shift, scale=scale)
        return np.minimum(np.abs(h - np.interp(y, yn, hn, left=0.0, right=0.0)), clip).mean()

    def search(signs, scales, shifts):
        return min((vertical_cost(sign, shift, scale), sign, scale, shift) for sign in signs for scale in scales for shift in shifts)

    reach = solid.width * max_scale
    _, sign, scale, shift = search((1, -1), np.arange(1.0, max_scale + 1e-9, 0.05), np.arange(y.min() - reach, y.max() + reach, 0.5))
    _, sign, scale, shift = search((sign,), np.arange(max(1.0, scale - 0.05), scale + 0.051, 0.01), np.arange(shift - 1.5, shift + 1.51, 0.1))
    far = (np.ptp(y) + 2 * solid.width) * max_scale
    best = min((np.minimum(distances(solid, sign, shift + d, y, h, pad=far, scale=max(1.0, scale + e)), clip).mean(),
                max(1.0, scale + e), shift + d) for d in np.arange(-0.5, 0.51, 0.1) for e in (-0.01, 0.0, 0.01))
    return sign, float(best[2]), float(best[1])


def nominal_curve(solid, sign, shift, pad=PAD, scale=1.0):
    """(y, h) of the nominal profile in the scan's reference frame, with ± `pad` mm of plane.

    `scale` stretches the profile along Y: a solid laid across the sheet is cut
    obliquely and its profile comes out stretched by 1/cos(angle) (see `align_oblique`).
    """
    x, h = solid.outline[::sign].T  # with the direction reversed the vertices are traversed from the right
    y = sign * scale * x + shift
    return np.concatenate([[y[0] - pad], y, [y[-1] + pad]]), np.concatenate([[0.0], h, [0.0]])


def distances(solid, sign, shift, y, h, step=0.05, pad=PAD, scale=1.0):
    """Distance (mm) of each measured point from the aligned nominal profile, measured in the
    (y, h) plane: unlike the height residual it does not amplify errors on steep flanks."""
    yn, hn = nominal_curve(solid, sign, shift, pad, scale)
    dense = np.vstack([np.linspace(a, b, max(2, int(np.hypot(*(b - a)) / step)))
                       for a, b in zip(np.column_stack([yn, hn])[:-1], np.column_stack([yn, hn])[1:])])
    return cKDTree(dense).query(np.column_stack([y, h]))[0]
